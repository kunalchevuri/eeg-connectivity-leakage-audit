"""Write 06_Manuscript/table_I_body.tex from coding_sheet_FINAL.csv - blueprint Sec 10/11:
Table I, corpus characteristics, one row per study: ID, dataset, subject count, connectivity
measure, architecture, partitioning unit, reported accuracy, rating.

ID is the \\cite{} key (from 07_References/bib_keys.csv, matched on DOI) rather than a bare
study_id, so a reviewer can trace every row straight to its reference - blueprint 12 still
requires KC to have opened that reference himself before submission.

Per blueprint Sec 7.5, ratings are reported per study here (that is what Table I is FOR:
"this is the paper's evidence base"), not aggregated - the aggregate-only rule in Sec 7.5
governs the manuscript's PROSE, not this table.

Usage (after 04_Phase4_Coding/build_final_coding_sheet.py has produced coding_sheet_FINAL.csv):
    python 06_Manuscript/build_table1.py
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
FINAL = ROOT / "04_Phase4_Coding/coding_sheet_FINAL.csv"
BIBKEYS = ROOT / "07_References/bib_keys.csv"
OUT = Path(__file__).parent / "table_I_body.tex"


def esc(s):
    return str(s).replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")


def main():
    if not FINAL.exists():
        print(f"{FINAL} does not exist yet - nothing to build. "
              f"paper.tex falls back to a PENDING placeholder until this is run.")
        return
    df = pd.read_csv(FINAL)
    if "accuracy_all_tasks" in df.columns:   # Table I reports every study's accuracy (advisor Q20)
        excluded = df["accuracy"].isna() & df["accuracy_all_tasks"].notna()
        df["accuracy"] = df["accuracy_all_tasks"]
        df["acc_mark"] = excluded.map({True: "$^{a}$", False: ""})
    keys = pd.read_csv(BIBKEYS) if BIBKEYS.exists() else pd.DataFrame(columns=["doi", "key_or_detail"])
    key_by_doi = dict(zip(keys["doi"].astype(str).str.strip().str.lower(),
                           keys["key_or_detail"]))

    rows = []
    missing_key = []
    for _, r in df.sort_values("study_id").iterrows():
        doi = str(r.get("doi", "")).strip().lower()
        key = key_by_doi.get(doi)
        if key:
            cite = f"\\cite{{{key}}}"
        else:
            cite = "\\PENDING{no bib key}"
            missing_key.append(r["study_id"])
        acc = r.get("accuracy")
        acc_s = (f"{float(acc):.1f}" if pd.notna(acc) else "--") + (r.get("acc_mark") if isinstance(r.get("acc_mark"), str) else "")
        rows.append(" & ".join([
            cite,
            esc(r.get("dataset", "--")),
            str(int(r["n_subjects"])) if pd.notna(r.get("n_subjects")) else "--",
            esc(r.get("connectivity_measure", "--")),
            esc(r.get("architecture", "--")),
            esc(r.get("split_unit", "--")),
            acc_s,
            esc(r.get("leakage_rating", "--")),
        ]) + r" \\")

    if missing_key:
        print(f"warning: {len(missing_key)} studies have no bib key yet (build_bib.py / bib_keys.csv): "
              f"{missing_key}. They render with a PENDING marker instead of a citation.")

    note = ""
    if "acc_mark" in df.columns and df["acc_mark"].eq("$^{a}$").any():
        note = ("\n" + r"\multicolumn{8}{l}{$^{a}$Not a binary depression-vs-control task; excluded from the primary "
                r"accuracy comparison (Section V-D).} \\")
    tex = r"""% GENERATED by build_table1.py from coding_sheet_FINAL.csv - do not edit by hand.
\begin{table*}[t]
\caption{Corpus characteristics, one row per included study; Study gives the reference number. Ratings describe what each paper reports, not how the study was conducted.}
\label{tab:corpus}
\centering
\scriptsize
\begin{tabular}{lllllrrl}
\toprule
Study & Dataset & $N$ subj. & Connectivity & Architecture & Partition unit & Acc.\ (\%) & \shortstack[l]{Risk rating from\\reported methods} \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule""" + note + r"""
\end{tabular}
\end{table*}
"""
    OUT.write_text(tex, encoding="utf-8")
    print(f"Wrote {OUT} ({len(rows)} rows).")


if __name__ == "__main__":
    main()
