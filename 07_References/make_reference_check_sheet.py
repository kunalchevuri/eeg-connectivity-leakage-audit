"""Build REFERENCE_CHECK_SHEET.xlsx: one row per bibliography entry, with its DOI link and every manuscript
sentence that cites it, so the person verifying references (blueprint Sec 12; advisor reminder 2026-09-24:
open every reference yourself) can check "does this paper support this sentence?" quickly.

AI does not verify anything here. It only places each claim next to its reference. The yellow columns are for
the person who opens the original. Also lists entries cited nowhere (candidates to drop toward the advisor's
cap of about 30 references) and the \\CITE{} placeholders still waiting for a reference.

    python 07_References/make_reference_check_sheet.py
"""
import re
from pathlib import Path

from openpyxl import Workbook, load_workbook
from openpyxl.styles import Alignment, Font, PatternFill

ROOT = Path(__file__).resolve().parents[1]
M = ROOT / "06_Manuscript"
OUT = Path(__file__).parent / "REFERENCE_CHECK_SHEET.xlsx"
CITE = re.compile(r"\\cite\{([^}]*)\}")
PLACEHOLDER = re.compile(r"\\CITE\{((?:[^{}]|\{[^{}]*\})*)\}")


def strip_comments(t):
    return re.sub(r"(?m)(?<!\\)%.*$", "", t)


def sentences(t):
    t = re.sub(r"\s+", " ", t)
    return re.split(r"(?<=[.!?])\s+(?=[A-Z\\])", t)


def clean(s):
    s = re.sub(r"\\(emph|textbf|textit)\{([^}]*)\}", r"\2", s)
    return s.strip()[:600]


def main():
    bib = (M / "references.bib").read_text(encoding="utf-8")
    entries = {}
    for m in re.finditer(r"@\w+\{([^,]+),(.*?)\n\}", bib, re.S):
        body = m.group(2)
        get = lambda f: (re.search(rf"\b{f}\s*=\s*\{{(.*?)\}},?\s*\n", body, re.S) or [None, ""])[1]
        entries[m.group(1).strip()] = {"title": re.sub(r"[{}\s]+", " ", get("title")).strip(),
                                       "author": re.sub(r"\s+", " ", get("author")),
                                       "year": get("year"), "doi": get("doi")}
    uses, placeholders = {}, []
    order = ["paper.tex", "section_I_body.tex", "section_II_body.tex", "section_III_body.tex", "section_IV_body.tex",
             "section_V_body.tex", "table_II_body.tex", "section_VII_body.tex", "section_VIII_body.tex"]
    for name in order:
        f = M / name
        if not f.exists():
            continue
        for s in sentences(strip_comments(f.read_text(encoding="utf-8"))):
            for m in CITE.finditer(s):
                for k in m.group(1).split(","):
                    uses.setdefault(k.strip(), []).append(f"[{name}] {clean(s)}")
            for m in PLACEHOLDER.finditer(s):
                placeholders.append((name, m.group(1), clean(s)))

    import csv
    corpus = {r["key_or_detail"] for r in csv.DictReader(open(Path(__file__).parent / "bib_keys.csv", encoding="utf-8"))
              if r["group"].startswith("corpus")}
    for k in corpus:   # every corpus study is cited in Table I (table_I_body.tex, generated by build_results.py)
        uses.setdefault(k, []).append("[Table I] corpus study - cited in the corpus-characteristics table")

    kept = {}   # the checker's y/n marks and notes survive a rebuild
    if OUT.exists():
        for r in load_workbook(OUT)["Check each reference"].iter_rows(min_row=2, values_only=True):
            if r[0]:
                kept[r[0]] = list(r[7:11])

    wb = Workbook()
    ws = wb.active
    ws.title = "Check each reference"
    head = ["bib_key", "authors", "year", "title", "doi link", "times cited", "sentence(s) that cite it",
            "opened original? (y/n)", "metadata correct? (y/n)", "supports EVERY sentence? (y/n)", "notes / fix needed"]
    ws.append(head)
    yellow = PatternFill("solid", fgColor="FFF2CC")
    for k, e in entries.items():
        s = uses.get(k, [])
        ws.append([k, e["author"], e["year"], e["title"], f"https://doi.org/{e['doi']}" if e["doi"] else "",
                   len(s), "\n\n".join(s) if s else "NOT CITED ANYWHERE - candidate to drop",
                   *kept.get(k, ["", "", "", ""])])
    for c in ws[1]:
        c.font = Font(bold=True)
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top")
        for c in row[7:]:
            c.fill = yellow
    for col, w in zip("ABCDEFGHIJK", [16, 28, 6, 40, 30, 7, 90, 10, 10, 12, 30]):
        ws.column_dimensions[col].width = w

    ph = wb.create_sheet("Placeholders still open")
    ph.append(["file", "what the placeholder asks for", "sentence"])
    for row in placeholders:
        ph.append(list(row))
    for c in ph[1]:
        c.font = Font(bold=True)
    for col, w in zip("ABC", [22, 60, 100]):
        ph.column_dimensions[col].width = w
    for row in ph.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top")

    wb.save(OUT)
    not_cited = [k for k in entries if k not in uses]
    missing = sorted(set(uses) - set(entries))
    print(f"{len(corpus)} corpus studies (cited in Table I), {len(entries) - len(corpus)} other references")
    print(f"{len(entries)} bib entries; {len(entries) - len(not_cited)} cited; {len(not_cited)} not cited: {not_cited}")
    print(f"{len(placeholders)} \\CITE placeholders open; cited keys missing from the bib: {missing or 'none'}")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
